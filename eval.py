#!/usr/bin/env python3
"""
eval.py — the FIXED scorecard for the Stage 1 autoresearch loop.

Do not edit this file or anything under data/ during an experiment. The agent
edits solution.py only, reruns this, and keeps changes that lower research_score.

    python3 eval.py            # human-readable report
    python3 eval.py --json     # machine-readable
    grep '^research_score:' <(python3 eval.py)

Dataset: data/bot_review.csv — LLM/human-reviewed bot recordings. Each scored row:
    transcript                 algorithm input (no harakat)
    ayah_assignment            gold ayah id/range/comma-list OR a non-Quran label
    confidence                 high | medium | low   (low excluded unless --score-low)
    transcript_split_by_ayahs  gold [{id, transcript}] split
    actual_ayahs               human reference only — NOT used for scoring

Score (lower is better):
    detection_error = 1 - (exact ayah-id-set matches / Quran rows)
    split_error     = 1 - mean(word-assignment accuracy / Quran rows)
    abstain_error   = 1 - (correct abstentions / non-Quran rows)
    research_score  = detection_error + split_error + abstain_error

Word-assignment accuracy = fraction of gold transcript words the algorithm placed
in the correct ayah bucket. A word counts only if it aligns to an identical
(canonicalized) predicted word AND that word got the same ayah id. The
canonicalizer below is metric-only — it is NOT the algorithm's normalizer.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import unicodedata
from dataclasses import asdict, dataclass, field
from difflib import SequenceMatcher
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))

from solution import Solution  # noqa: E402  (the editable algorithm)

DEFAULT_CSV = HERE / "data/bot_review.csv"
SCORED_CONFIDENCE = {"high", "medium"}
ASSIGNMENT_RE = re.compile(r"^\d{6}(?:-\d{6})?(?:,\d{6}(?:-\d{6})?)*$")
_HARAKAT_RE = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭ]")
_FOLD = {"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ى": "ي", "ؤ": "ء", "ئ": "ء"}


def canon(text: str) -> list[str]:
    """Metric-only canonicalization: fold orthographic variants, drop harakat,
    so spelling noise (آ/ا, leftover diacritics, Uthmani forms) is not scored as
    a split error. Returns a token list."""
    text = unicodedata.normalize("NFKC", text or "")
    text = text.replace("ـ", "")  # tatweel
    for a, b in _FOLD.items():
        text = text.replace(a, b)
    text = _HARAKAT_RE.sub("", text)
    return text.split()


def expand_assignment(assignment: str) -> list[str]:
    """Expand Quran assignment syntax into unique ids.

    Examples:
      '095001' -> ['095001']
      '095001-095003' -> ['095001', '095002', '095003']
      '075001,075002,075004' -> ['075001', '075002', '075004']
    """
    assignment = assignment.strip()
    if not ASSIGNMENT_RE.match(assignment):
        return []
    ids: list[str] = []
    for part in assignment.split(","):
        if "-" not in part:
            expanded = [part]
        else:
            start, end = part.split("-", 1)
            if start[:3] != end[:3]:
                expanded = [start, end]  # cross-surah: treated as non-exact
            else:
                expanded = [f"{start[:3]}{i:03d}" for i in range(int(start[3:]), int(end[3:]) + 1)]
        for ayah_id in expanded:
            if ayah_id not in ids:
                ids.append(ayah_id)
    return ids


def token_labels(segments: list[tuple[str, str]]) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for ayah_id, text in segments:
        for tok in canon(text):
            out.append((tok, ayah_id))
    return out


def word_assignment_accuracy(
    gold_segments: list[tuple[str, str]],
    pred_segments: list[tuple[str, str]],
) -> float:
    gold = token_labels(gold_segments)
    pred = token_labels(pred_segments)
    if not gold or not pred:
        return 0.0
    matcher = SequenceMatcher(a=[t for t, _ in gold], b=[t for t, _ in pred], autojunk=False)
    correct = 0
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag != "equal":
            continue
        for k in range(i2 - i1):
            if gold[i1 + k][1] == pred[j1 + k][1]:
                correct += 1
    return correct / len(gold)


@dataclass
class CaseResult:
    recording_id: str
    kind: str  # "range" | "abstain"
    confidence: str
    expected_ayah_ids: list[str]
    predicted_ayah_ids: list[str] = field(default_factory=list)
    detection_exact: bool = False
    split_accuracy: float | None = None
    abstain_correct: bool | None = None
    error: str | None = None


def parse_split(raw: str) -> list[tuple[str, str]]:
    if not raw:
        return []
    return [(s["id"], s.get("transcript", "")) for s in json.loads(raw)]


def evaluate_row(row: dict[str, str], solution: Solution) -> CaseResult:
    rec_id = row.get("recording_id", "")
    confidence = (row.get("confidence") or "").strip().lower()
    assignment = (row.get("ayah_assignment") or "").strip()
    transcript = row.get("transcript") or ""
    expected = expand_assignment(assignment)
    is_range = bool(expected)

    try:
        result = solution.process(transcript) or {}
    except Exception as exc:  # keep algorithm crashes visible, don't abort the run
        return CaseResult(rec_id, "range" if is_range else "abstain", confidence, expected, error=str(exc))

    abstained = bool(result.get("abstain"))
    pred_ayahs = result.get("ayahs") or []
    predicted_ids = [a["id"] for a in pred_ayahs]

    if not is_range:
        return CaseResult(
            recording_id=rec_id, kind="abstain", confidence=confidence,
            expected_ayah_ids=[], predicted_ayah_ids=predicted_ids,
            abstain_correct=abstained,
        )

    pred_segments = [(a["id"], a.get("text", "")) for a in pred_ayahs]
    gold_segments = parse_split(row.get("transcript_split_by_ayahs") or "")
    # Detection is about *which* ayahs were recited, so compare sets.
    # A reciter may repeat ayahs (e.g. Al-Ikhlas ×3); that is a split concern, not
    # a detection error. Split is only scored when a gold split was recorded.
    split_accuracy = (
        round(word_assignment_accuracy(gold_segments, pred_segments), 4)
        if gold_segments else None
    )

    return CaseResult(
        recording_id=rec_id, kind="range", confidence=confidence,
        expected_ayah_ids=expected, predicted_ayah_ids=predicted_ids,
        detection_exact=sorted(set(predicted_ids)) == expected,
        split_accuracy=split_accuracy,
    )


def summarize(results: list[CaseResult]) -> dict[str, Any]:
    range_cases = [r for r in results if r.kind == "range"]
    abstain_cases = [r for r in results if r.kind == "abstain"]
    detection_exact = sum(1 for r in range_cases if r.detection_exact)
    split_values = [r.split_accuracy for r in range_cases if r.split_accuracy is not None]
    abstain_correct = sum(1 for r in abstain_cases if r.abstain_correct)

    detection_accuracy = detection_exact / max(len(range_cases), 1)
    mean_split = sum(split_values) / max(len(split_values), 1)
    abstain_accuracy = abstain_correct / max(len(abstain_cases), 1)

    detection_error = (1 - detection_accuracy) if range_cases else 0.0
    split_error = (1 - mean_split) if split_values else 0.0
    abstain_error = (1 - abstain_accuracy) if abstain_cases else 0.0

    return {
        "research_score": round(detection_error + split_error + abstain_error, 6),
        "score_direction": "lower_is_better",
        "stage": "1_detection_and_split",
        "cases": len(results),
        "detection": {"exact": detection_exact, "total": len(range_cases), "accuracy": round(detection_accuracy, 4)},
        "split": {"mean_word_assignment_accuracy": round(mean_split, 4), "scored_cases": len(split_values)},
        "abstain": {"correct": abstain_correct, "total": len(abstain_cases), "accuracy": round(abstain_accuracy, 4)},
    }


def print_report(summary: dict[str, Any], results: list[CaseResult]) -> None:
    print("---")
    print(f"research_score:   {summary['research_score']:.6f}")
    print(f"score_direction:  {summary['score_direction']}")
    print()
    print("Stage 1 scorecard (detection + split)")
    print(f"  Cases: {summary['cases']}")
    d, s, a = summary["detection"], summary["split"], summary["abstain"]
    print(f"  Detection exact:  {d['exact']}/{d['total']} ({d['accuracy']:.1%})")
    print(f"  Split accuracy:   {s['mean_word_assignment_accuracy']:.1%} (word-assignment, {s['scored_cases']} cases)")
    print(f"  Abstain correct:  {a['correct']}/{a['total']} ({a['accuracy']:.1%}) [non-Quran]")

    failures = [
        r for r in results
        if r.error
        or (r.kind == "range" and (not r.detection_exact or (r.split_accuracy or 0) < 0.999))
        or (r.kind == "abstain" and not r.abstain_correct)
    ]
    if failures:
        print(f"  Failures ({len(failures)}):")
        for r in failures[:40]:
            tag = r.recording_id[:8]
            if r.error:
                print(f"    {tag} ERROR: {r.error}")
            elif r.kind == "abstain":
                print(f"    {tag} abstain: expected none, got {r.predicted_ayah_ids or '∅'}")
            else:
                sp = f"split={r.split_accuracy:.2f}" if r.split_accuracy is not None else "split=-"
                print(f"    {tag} range: expected {r.expected_ayah_ids} got {r.predicted_ayah_ids or '∅'} {sp}")
        if len(failures) > 40:
            print(f"    ... {len(failures) - 40} more")


def load_rows(path: Path, *, score_low: bool) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if score_low:
        return rows
    return [r for r in rows if (r.get("confidence") or "").strip().lower() in SCORED_CONFIDENCE]


def main() -> int:
    parser = argparse.ArgumentParser(description="Stage 1 autoresearch scorecard.")
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    parser.add_argument("--score-low", action="store_true", help="Include low-confidence rows")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    solution = Solution()
    rows = load_rows(args.csv, score_low=args.score_low)
    results = [evaluate_row(row, solution) for row in rows]
    summary = summarize(results)

    if args.json:
        print(json.dumps({"summary": summary, "cases": [asdict(r) for r in results]}, ensure_ascii=False, indent=2))
    else:
        print_report(summary, results)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
